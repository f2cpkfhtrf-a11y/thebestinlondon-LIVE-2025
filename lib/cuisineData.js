// Helper function to get cuisine data with fallback
export function getCuisineData(cuisineSlug) {
  const normalizedSlug = cuisineSlug.toLowerCase().replace(/\s+/g, '-');
  return cuisineData[normalizedSlug] || {
    slug: normalizedSlug,
    name: normalizedSlug.split('-').map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' '),
    heroImage: "/images/heroes/cuisines/british.webp",
    heroAlt: `${normalizedSlug} cuisine in London`,
    intro: `Explore London's finest ${normalizedSlug} restaurants, carefully curated for exceptional quality and authentic flavors.`
  };
}
